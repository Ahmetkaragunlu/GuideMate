package com.ahmetkaragunlu.guidemate.common.result

enum class BackendErrorCode {
    // Account and credentials
    USER_NOT_FOUND,
    EMAIL_ALREADY_EXISTS,
    ACCOUNT_PENDING_VERIFICATION,
    ACCOUNT_DISABLED,
    INVALID_CREDENTIALS,
    CURRENT_PASSWORD_INCORRECT,
    PASSWORD_POLICY_VIOLATION,
    PASSWORD_SAME_AS_CURRENT,
    PASSWORDS_DO_NOT_MATCH,
    ROLE_ALREADY_SELECTED,
    ROLE_NOT_FOUND,

    // Installation and token lifecycle
    INVALID_INSTALLATION_ID,
    INVALID_TOKEN,
    TOKEN_EXPIRED,
    TOKEN_ALREADY_USED,
    INVALID_REFRESH_TOKEN,
    REFRESH_TOKEN_EXPIRED,
    REFRESH_TOKEN_REPLAY,

    // Google authentication
    GOOGLE_LOGIN_FAILED,
    GOOGLE_ACCOUNT_NOT_FOUND,
    GOOGLE_ACCOUNT_MISMATCH,

    // Shared request failures
    UNAUTHORIZED,
    FORBIDDEN,
    VALIDATION_FAILED,
    MALFORMED_REQUEST,
    DATA_CONFLICT,
    RATE_LIMITED,
    EMAIL_DELIVERY_FAILED,

    // Media and guide profile
    MEDIA_NOT_FOUND,
    MEDIA_INVALID_TYPE,
    MEDIA_TOO_LARGE,
    MEDIA_STORAGE_FAILED,
    MEDIA_IN_USE,
    MEDIA_PURPOSE_MISMATCH,
    GUIDE_PROFILE_NOT_FOUND,
    INVALID_LANGUAGE_CODE,

    // Tour lifecycle and metadata
    TOUR_NOT_FOUND,
    TOUR_NOT_APPROVED,
    TOUR_CHANGE_PENDING,
    TOUR_LOCATION_LOCKED,
    TOUR_NOT_ARCHIVABLE,
    TOUR_REVIEW_NOT_FOUND,
    TOUR_REVIEW_STATE_INVALID,
    INVALID_CATEGORY_CODE,
    INVALID_COUNTRY_CODE,
    INVALID_TIME_ZONE,

    // Tour sessions and capacity
    SESSION_NOT_FOUND,
    SESSION_NOT_BOOKABLE,
    SESSION_ALREADY_STARTED,
    SESSION_HAS_RESERVATIONS,
    CAPACITY_NOT_AVAILABLE,
    CAPACITY_BELOW_BOOKED_COUNT,
    SESSION_STATUS_NOT_MANAGEABLE,
    SCHEDULE_CONFLICT,
    CONCURRENT_UPDATE,

    // Reservations and reviews
    RESERVATION_NOT_FOUND,
    RESERVATION_ALREADY_EXISTS,
    RESERVATION_NOT_CANCELLABLE,
    REVIEW_NOT_ALLOWED,
    REVIEW_ALREADY_EXISTS,

    // Payments and foreign exchange
    IDEMPOTENCY_CONFLICT,
    PAYMENT_NOT_FOUND,
    PAYMENT_INITIALIZATION_FAILED,
    PAYMENT_VERIFICATION_FAILED,
    PAYMENT_NOT_CANCELLABLE,
    PAYMENT_CURRENCY_NOT_SUPPORTED,
    FX_QUOTE_UNAVAILABLE,
    FX_QUOTE_EXPIRED,
    CARD_INSUFFICIENT_FUNDS,
    PAYMENT_METHOD_DECLINED,
    INVALID_AMOUNT,

    // Wallet, bank accounts, saved cards, and refunds
    INSUFFICIENT_WALLET_BALANCE,
    INSUFFICIENT_WITHDRAWABLE_BALANCE,
    BANK_ACCOUNT_NOT_FOUND,
    BANK_ACCOUNT_INVALID,
    BANK_ACCOUNT_ALREADY_EXISTS,
    SAVED_CARD_NOT_FOUND,
    SAVED_CARD_SYNC_FAILED,
    SAVED_CARD_PROVIDER_UNAVAILABLE,
    REFUND_FAILED,
    REFUND_AMOUNT_EXCEEDED,

    // Notifications and chat
    NOTIFICATION_NOT_FOUND,
    CHAT_NOT_FOUND,
    CHAT_PARTICIPANT_INVALID,
    CHAT_MESSAGE_NOT_FOUND,
    CHAT_MESSAGE_TOO_LONG,

    // Unexpected server failures
    INTERNAL_SERVER_ERROR,
    ;

    companion object {
        fun from(value: String?): BackendErrorCode? =
            entries.firstOrNull { it.name == value }
    }
}
